// Builds supabase/manual/approve-request-dashboard/approve_request_bundle.ts —
// a single file that can be pasted into Supabase Dashboard → Edge Functions → approve-request.
// Usage: node scripts/bundle-approve-request.mjs
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const fn = join(root, 'supabase/functions');
const out = join(root, 'supabase/manual/approve-request-dashboard');

const strip = (src) => src.split(/\r?\n/).filter((l) => !/^import\s/.test(l)).join('\n');
const common = readFileSync(join(fn, '_shared/common.ts'), 'utf8');
const stamp = readFileSync(join(fn, 'approve-request/stamp.ts'), 'utf8');
const index = readFileSync(join(fn, 'approve-request/index.ts'), 'utf8');

const bundle = [
  '// ============================================================================',
  '// STANDALONE SINGLE-FILE EDGE FUNCTION: approve-request',
  '// Ready to paste into Supabase Dashboard -> Edge Functions -> approve-request',
  '// (generated by scripts/bundle-approve-request.mjs — do not edit by hand)',
  '// ============================================================================',
  'import { createClient, type SupabaseClient } from "npm:@supabase/supabase-js@2.49.4";',
  'import { degrees, PDFDocument, type PDFFont, type PDFImage, type PDFPage, rgb, StandardFonts } from "npm:pdf-lib@1.17.1";',
  'import QRCode from "npm:qrcode@1.5.4";',
  '',
  '// --- common.ts ---',
  strip(common),
  '',
  '// --- stamp.ts ---',
  strip(stamp),
  '',
  '// --- index.ts ---',
  strip(index),
  '',
].join('\n');

writeFileSync(join(out, 'approve_request_bundle.ts'), bundle);
copyFileSync(join(fn, '_shared/common.ts'), join(out, 'common.ts'));
copyFileSync(join(fn, 'approve-request/stamp.ts'), join(out, 'stamp.ts'));
copyFileSync(join(fn, 'approve-request/index.ts'), join(out, 'index.ts'));
console.log(`approve_request_bundle.ts written (${bundle.length} bytes)`);

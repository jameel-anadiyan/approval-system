import { useEffect, useState } from 'react';
import { supabase } from './supabase';

export type Bucket = 'request-files' | 'signed-documents' | 'profile-photos';

const URL_TTL_SEC = 60 * 10;

/** Short-lived signed URL for a private object (RLS on storage decides access). */
export async function getSignedUrl(
  bucket: Bucket,
  path: string,
  downloadAs?: string
): Promise<{ url: string | null; error?: string }> {
  if (path.startsWith('data:') || path.startsWith('http://') || path.startsWith('https://')) {
    return { url: path };
  }
  const { data, error } = await supabase.storage
    .from(bucket)
    .createSignedUrl(path, URL_TTL_SEC, downloadAs ? { download: downloadAs } : undefined);
  if (error || !data?.signedUrl) return { url: null, error: error?.message || 'File not available' };
  return { url: data.signedUrl };
}

/** Triggers a browser download of a private object. */
export async function downloadStoredFile(
  bucket: Bucket,
  path: string,
  fileName: string
): Promise<{ success: boolean; error?: string }> {
  const { url, error } = await getSignedUrl(bucket, path, fileName);
  if (!url) return { success: false, error };
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  a.rel = 'noopener';
  document.body.appendChild(a);
  a.click();
  a.remove();
  return { success: true };
}

/** Downloads the combined signed packet (falls back to the first signed file). */
export async function downloadSignedPacket(
  request: { approval_no: string | null; signed_files?: { storage_path: string; file_name?: string; is_packet?: boolean }[] },
  live: boolean
): Promise<{ success: boolean; error?: string }> {
  if (!live) return { success: false, error: 'Sandbox mode: signed PDFs are only generated by the live server.' };
  const packet = request.signed_files?.find((s) => s.is_packet) || request.signed_files?.[0];
  if (!packet) return { success: false, error: 'Signed packet not available yet.' };
  return downloadStoredFile('signed-documents', packet.storage_path, packet.file_name || `${request.approval_no || 'approval'}_packet.pdf`);
}

/** Resolves a signed URL for previews (images, PDFs, audio). Returns null in sandbox mode. */
export function useSignedUrl(bucket: Bucket, path: string | undefined | null, live: boolean) {
  const [state, setState] = useState<{ url: string | null; loading: boolean; error?: string }>({
    url: null,
    loading: false,
  });

  useEffect(() => {
    let cancelled = false;
    if (!path) {
      setState({ url: null, loading: false });
      return;
    }
    // Direct data or web URL (e.g. mock or newly uploaded preview)
    if (path.startsWith('data:') || path.startsWith('http://') || path.startsWith('https://')) {
      setState({ url: path, loading: false });
      return;
    }
    if (!live) {
      setState({ url: null, loading: false });
      return;
    }
    setState({ url: null, loading: true });
    getSignedUrl(bucket, path).then((res) => {
      if (!cancelled) setState({ url: res.url, loading: false, error: res.error });
    });
    return () => {
      cancelled = true;
    };
  }, [bucket, path, live]);

  return state;
}


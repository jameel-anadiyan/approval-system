import { PDFDocument, rgb, StandardFonts, type PDFFont } from 'pdf-lib';
import type { RequestRecord } from '../types/database';
import { formatFileSize, formatISTDate } from './formatters';

function toSafePdfText(str: unknown): string {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/₹/g, 'Rs. ')
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/\u2026/g, '...')
    .replace(/\u00A0/g, ' ')
    .replace(/[^\x20-\x7E\xA0-\xFF]/g, ' ');
}

function wrapText(text: string, font: PDFFont, fontSize: number, maxWidth: number): string[] {
  const safe = toSafePdfText(text).trim() || '-';
  const paragraphs = safe.split(/\r?\n/);
  const lines: string[] = [];

  for (const para of paragraphs) {
    const words = para.split(/\s+/).filter(Boolean);
    if (words.length === 0) {
      lines.push('');
      continue;
    }
    let current = words[0];
    for (let i = 1; i < words.length; i++) {
      const candidate = `${current} ${words[i]}`;
      if (font.widthOfTextAtSize(candidate, fontSize) <= maxWidth) {
        current = candidate;
      } else {
        lines.push(current);
        current = words[i];
      }
    }
    lines.push(current);
  }
  return lines;
}

export function isAutoGeneratedSpecialForm(fileName?: string | null): boolean {
  if (!fileName) return false;
  const lower = fileName.toLowerCase();
  return (
    lower.startsWith('agreement_approval_form') ||
    lower.startsWith('statutory_payment_approval_form') ||
    lower.startsWith('audit_report_approval_form') ||
    lower.startsWith('exhibition_event_approval_form')
  );
}

export function specialRequestFormFileName(type?: string | null): string {
  if (type === 'agreement') return 'Agreement_Approval_Form.pdf';
  if (type === 'statutory_payment') return 'Statutory_Payment_Approval_Form.pdf';
  if (type === 'audit_report') return 'Audit_Report_Approval_Form.pdf';
  return 'Official_Approval_Form.pdf';
}

/**
 * Generates the official A4 PDF form for Agreement, Statutory Payment, and Audit Report requests.
 * Synced to `request_files` (`sort_order = -1`) so both web approval and WhatsApp approval
 * always have a clean, stampable official PDF even when all user attachments are Excel/Word files.
 */
export async function generateSpecialRequestFormPdf(
  req: Pick<
    RequestRecord,
    | 'request_type'
    | 'request_no'
    | 'title'
    | 'requester_name'
    | 'shop_name'
    | 'owner_head_name'
    | 'assigned_entry_user_name'
    | 'disbursement_mode'
    | 'amount'
    | 'notes'
    | 'details'
    | 'files'
    | 'submitted_at'
    | 'created_at'
    | 'bank_account_holder_name'
    | 'bank_account_no'
    | 'bank_ifsc'
    | 'bank_name'
    | 'enter_bank_details_later'
  > & { department_name?: string | null }
): Promise<{ bytes: Uint8Array; blob: Blob; pageCount: number; fileName: string }> {
  const pdfDoc = await PDFDocument.create();
  const regular = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const bold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  const pageWidth = 595.28; // A4 width
  const pageHeight = 841.89; // A4 height
  const margin = 42;
  const contentWidth = pageWidth - margin * 2;
  const page = pdfDoc.addPage([pageWidth, pageHeight]);

  const type = req.request_type || 'agreement';
  const fileName = specialRequestFormFileName(type);
  const d = req.details ?? {};

  const theme =
    type === 'statutory_payment'
      ? {
          primary: rgb(0.68, 0.27, 0.05),
          subText: rgb(0.99, 0.91, 0.84),
          rowAlt: rgb(0.995, 0.98, 0.965),
          subtitle: 'STATUTORY PAYMENT APPROVAL FORM',
          badge: `Rs. ${Number(d.payment_amount ?? req.amount ?? 0).toLocaleString('en-IN', {
            minimumFractionDigits: 2,
            maximumFractionDigits: 2,
          })}`,
          sectionTitle: '1. STATUTORY PAYMENT REQUEST DETAILS',
          footer:
            'Workflow: Route B — Department Head Approval Only (Admin Approval Not Required) · Payable via Disbursement',
        }
      : type === 'audit_report'
        ? {
            primary: rgb(0.06, 0.34, 0.45),
            subText: rgb(0.85, 0.95, 0.99),
            rowAlt: rgb(0.965, 0.985, 0.995),
            subtitle: 'AUDIT REPORT APPROVAL FORM',
            badge: 'Non-Cash · Admin Approval',
            sectionTitle: '1. AUDIT REPORT DETAILS',
            footer:
              'Workflow: Route A — Administrator Approval Only · Non-Cash Request (No Disbursement Needed)',
          }
        : {
            primary: rgb(0.32, 0.18, 0.58),
            subText: rgb(0.91, 0.87, 0.99),
            rowAlt: rgb(0.98, 0.97, 0.995),
            subtitle: 'AGREEMENT APPROVAL FORM',
            badge: 'Non-Cash · Head Approval',
            sectionTitle: '1. AGREEMENT REQUEST DETAILS',
            footer:
              'Workflow: Route B — Department Head Approval Only (Admin Approval Not Required) · Non-Cash (No Disbursement)',
          };

  // Top Banner
  const bannerHeight = 68;
  const bannerTop = pageHeight - margin;
  page.drawRectangle({
    x: margin,
    y: bannerTop - bannerHeight,
    width: contentWidth,
    height: bannerHeight,
    color: theme.primary,
  });

  page.drawText('SWA DIAMONDS', {
    x: margin + 18,
    y: bannerTop - 27,
    size: 16,
    font: bold,
    color: rgb(1, 1, 1),
  });

  page.drawText(theme.subtitle, {
    x: margin + 18,
    y: bannerTop - 48,
    size: 11,
    font: bold,
    color: theme.subText,
  });

  const badgeText = toSafePdfText(theme.badge);
  const badgeTextW = bold.widthOfTextAtSize(badgeText, 10);
  const pillW = badgeTextW + 22;
  page.drawRectangle({
    x: margin + contentWidth - pillW - 14,
    y: bannerTop - 46,
    width: pillW,
    height: 25,
    color: rgb(1, 1, 1),
  });
  page.drawText(badgeText, {
    x: margin + contentWidth - pillW - 3,
    y: bannerTop - 37,
    size: 10,
    font: bold,
    color: theme.primary,
  });

  let y = bannerTop - bannerHeight - 20;

  page.drawText(theme.sectionTitle, {
    x: margin,
    y,
    size: 9.8,
    font: bold,
    color: theme.primary,
  });
  y -= 9;

  const rows: [string, string][] = [
    ['Request Number', toSafePdfText(req.request_no || 'Pending Assignment')],
    ['Submitted Date', toSafePdfText(formatISTDate(req.submitted_at || req.created_at, true))],
    ['Title / Subject', toSafePdfText(req.title || '-')],
    ['Requested By', toSafePdfText(req.requester_name || '-')],
    ['Department / Head', toSafePdfText(req.department_name || req.owner_head_name || '-')],
    ['Outlet / Shop', toSafePdfText(req.shop_name || 'Not Assigned')],
  ];

  if (type === 'agreement') {
    rows.push(['Consideration', 'Non-Cash Item (No Disbursement Required)']);
    rows.push(['Approval Authority', 'Department Head Approval Only (Route B)']);
  } else if (type === 'statutory_payment') {
    const payAmt = Number(d.payment_amount ?? req.amount ?? 0);
    const formattedAmt = `Rs. ${payAmt.toLocaleString('en-IN', {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })}`;
    const modeLabel =
      (req.disbursement_mode || d.disbursement_mode || '').toLowerCase() === 'bank'
        ? 'Bank Transfer'
        : (req.disbursement_mode || d.disbursement_mode || '').toLowerCase() === 'cash'
          ? 'Cash'
          : 'Standard Disbursement';
    rows.push(['Payment Amount', formattedAmt]);
    rows.push(['Payment Date', toSafePdfText(d.payment_date || '-')]);
    rows.push(['Due Date', toSafePdfText(d.due_date || '-')]);
    rows.push(['Payment Mode', modeLabel]);
    if (req.assigned_entry_user_name) {
      rows.push(['Disbursement Entry Account', toSafePdfText(req.assigned_entry_user_name)]);
    }
    if ((req.disbursement_mode || d.disbursement_mode || '').toLowerCase() === 'bank') {
      if (req.enter_bank_details_later) {
        rows.push(['Bank Account Details', 'To be entered during Disbursement']);
      } else if (req.bank_account_no) {
        rows.push([
          'Beneficiary Bank Account',
          toSafePdfText(
            `${req.bank_account_holder_name || ''} | A/C: ${req.bank_account_no} | IFSC: ${req.bank_ifsc || '-'} (${req.bank_name || '-'})`
          ),
        ]);
      }
    }
    rows.push(['Approval Authority', 'Department Head Approval Only (Route B)']);
  } else if (type === 'audit_report') {
    rows.push(['Audit Report of Which Firm', toSafePdfText(d.audit_firm || '-')]);
    rows.push([
      'Audit Period (From - To)',
      toSafePdfText(`${d.audit_from_date || '-'}  to  ${d.audit_to_date || '-'}`),
    ]);
    rows.push(['Consideration', 'Non-Cash Item (No Disbursement Required)']);
    rows.push(['Approval Authority', 'Administrator Approval Only (Route A)']);
  }

  const labelColWidth = 175;
  const rowHeight = 22;

  rows.forEach(([label, val], idx) => {
    const rowTop = y;
    const rowBottom = rowTop - rowHeight;
    page.drawRectangle({
      x: margin,
      y: rowBottom,
      width: contentWidth,
      height: rowHeight,
      color: idx % 2 === 0 ? theme.rowAlt : rgb(1, 1, 1),
      borderColor: rgb(0.85, 0.88, 0.91),
      borderWidth: 0.6,
    });
    page.drawLine({
      start: { x: margin + labelColWidth, y: rowTop },
      end: { x: margin + labelColWidth, y: rowBottom },
      thickness: 0.6,
      color: rgb(0.85, 0.88, 0.91),
    });
    page.drawText(label, {
      x: margin + 10,
      y: rowBottom + 7,
      size: 9,
      font: bold,
      color: rgb(0.25, 0.3, 0.36),
    });

    const isHighlight =
      label === 'Payment Amount' ||
      label === 'Audit Report of Which Firm' ||
      label === 'Title / Subject';
    const valLines = wrapText(
      val || '-',
      isHighlight ? bold : regular,
      9.2,
      contentWidth - labelColWidth - 20
    );
    page.drawText(valLines[0] || '-', {
      x: margin + labelColWidth + 10,
      y: rowBottom + 7,
      size: 9.2,
      font: isHighlight ? bold : regular,
      color: isHighlight ? theme.primary : rgb(0.1, 0.13, 0.18),
    });
    y = rowBottom;
  });

  // Section 2: Description
  y -= 18;
  page.drawText('2. DESCRIPTION / DETAILS', {
    x: margin,
    y,
    size: 9.8,
    font: bold,
    color: theme.primary,
  });
  y -= 9;

  const descText = req.notes || d.description || '-';
  const descLines = wrapText(descText, regular, 9.6, contentWidth - 24).slice(0, 11);
  const descBoxHeight = Math.max(54, descLines.length * 13 + 18);
  page.drawRectangle({
    x: margin,
    y: y - descBoxHeight,
    width: contentWidth,
    height: descBoxHeight,
    color: rgb(0.995, 0.995, 0.998),
    borderColor: rgb(0.82, 0.85, 0.9),
    borderWidth: 0.7,
  });

  let textY = y - 16;
  for (const line of descLines) {
    page.drawText(line, {
      x: margin + 12,
      y: textY,
      size: 9.6,
      font: regular,
      color: rgb(0.12, 0.15, 0.2),
    });
    textY -= 13;
  }
  y = y - descBoxHeight;

  // Section 3: Supporting Attachments Summary (includes Excel, Word, PDF, Images)
  const userDocs = (req.files || []).filter(
    (f) => f.kind === 'document' && !isAutoGeneratedSpecialForm(f.original_name)
  );
  if (userDocs.length > 0 && y > 180) {
    y -= 18;
    page.drawText(`3. ATTACHED SUPPORTING DOCUMENTS (${userDocs.length})`, {
      x: margin,
      y,
      size: 9.8,
      font: bold,
      color: theme.primary,
    });
    y -= 9;

    const maxDocs = Math.min(userDocs.length, 6);
    for (let i = 0; i < maxDocs; i++) {
      const doc = userDocs[i];
      const rTop = y;
      const rBot = rTop - 19;
      page.drawRectangle({
        x: margin,
        y: rBot,
        width: contentWidth,
        height: 19,
        color: i % 2 === 0 ? theme.rowAlt : rgb(1, 1, 1),
        borderColor: rgb(0.86, 0.89, 0.92),
        borderWidth: 0.5,
      });
      const lineStr = toSafePdfText(
        `${i + 1}. ${doc.original_name} (${formatFileSize(doc.size_bytes || 0)})`
      );
      const clipped = wrapText(lineStr, regular, 8.8, contentWidth - 20)[0] || lineStr;
      page.drawText(clipped, {
        x: margin + 10,
        y: rBot + 6,
        size: 8.8,
        font: regular,
        color: rgb(0.15, 0.18, 0.24),
      });
      y = rBot;
    }
    if (userDocs.length > maxDocs) {
      y -= 13;
      page.drawText(`+ ${userDocs.length - maxDocs} more attached file(s) in request record`, {
        x: margin + 4,
        y,
        size: 8.5,
        font: regular,
        color: rgb(0.42, 0.46, 0.52),
      });
    }
  }

  y -= 16;
  page.drawText(theme.footer, {
    x: margin,
    y: Math.max(margin + 10, y),
    size: 8.2,
    font: regular,
    color: rgb(0.42, 0.47, 0.52),
  });

  const bytes = await pdfDoc.save();
  const blob = new Blob([bytes as BlobPart], { type: 'application/pdf' });
  return { bytes, blob, pageCount: pdfDoc.getPageCount(), fileName };
}

import { PDFDocument, rgb, StandardFonts, type PDFFont } from 'pdf-lib';
import type { RequestRecord, ExhibitionDaySchedule } from '../types/database';
import { formatISTDate } from './formatters';

export const EXHIBITION_FORM_FILE_NAME = 'Exhibition_Event_Approval_Form.pdf';

export function isAutoGeneratedExhibitionForm(fileName?: string | null): boolean {
  if (!fileName) return false;
  const lower = fileName.toLowerCase();
  return lower.startsWith('exhibition_event_approval_form');
}

function toSafePdfText(str: unknown): string {
  if (str === null || str === undefined) return '';
  return String(str)
    .replace(/₹/g, 'Rs. ')
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/\u2026/g, '...')
    .replace(/\u00A0/g, ' ')
    .replace(/[^\x20-\x7E\xA0-\xFF]/g, ' ');
}

function wrapText(text: string, font: PDFFont, fontSize: number, maxWidth: number): string[] {
  const safe = toSafePdfText(text).trim() || '-';
  const paragraphs = safe.split(/\r?\n/);
  const lines: string[] = [];

  for (const para of paragraphs) {
    const words = para.split(/\s+/).filter(Boolean);
    if (words.length === 0) {
      lines.push('');
      continue;
    }
    let current = words[0];
    for (let i = 1; i < words.length; i++) {
      const candidate = `${current} ${words[i]}`;
      if (font.widthOfTextAtSize(candidate, fontSize) <= maxWidth) {
        current = candidate;
      } else {
        lines.push(current);
        current = words[i];
      }
    }
    lines.push(current);
  }
  return lines;
}

const PROVIDE_NAMES: Record<string, string> = {
  stall_space: 'Stall Space',
  table_chairs: 'Table & Chairs',
  electricity_lights: 'Electricity / Lights',
  logo_stage_banners: 'Logo on Stage & Banners',
  stage_announcements: 'Stage Announcements',
  social_media: 'Social Media Promotion',
  other: 'Other Provisions',
};

/**
 * Generates the official A4 PDF form for Exhibition / Event Sponsorship requests.
 * Synced to `request_files` (`sort_order = -1`) so the form can be previewed before sealing
 * and stamped with official seal, signature, QR code, and Approval No upon approval.
 */
export async function generateExhibitionFormPdf(
  req: Pick<
    RequestRecord,
    | 'request_no'
    | 'title'
    | 'requester_name'
    | 'shop_name'
    | 'owner_head_name'
    | 'assigned_entry_user_name'
    | 'disbursement_mode'
    | 'amount'
    | 'notes'
    | 'details'
    | 'submitted_at'
    | 'created_at'
  > & { department_name?: string | null }
): Promise<{ bytes: Uint8Array; blob: Blob; pageCount: number; fileName: string }> {
  const pdfDoc = await PDFDocument.create();
  const regular = await pdfDoc.embedFont(StandardFonts.Helvetica);
  const bold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);

  const pageWidth = 595.28; // A4 width
  const pageHeight = 841.89; // A4 height
  const margin = 38;
  const contentWidth = pageWidth - margin * 2;
  const page = pdfDoc.addPage([pageWidth, pageHeight]);

  const d = req.details ?? {};
  const schedules: ExhibitionDaySchedule[] = Array.isArray(d.daily_schedules) ? d.daily_schedules : [];
  const totalDays = schedules.length > 0 ? schedules.length : Number(d.total_days || 1);
  const totalHours = schedules.reduce((s, row) => s + (Number(row.hours) || 0), 0) || Number(d.total_hours || 0);

  const theme = {
    primary: rgb(0.12, 0.18, 0.42), // Deep Indigo
    subText: rgb(0.92, 0.94, 0.99),
    rowAlt: rgb(0.97, 0.98, 1.0),
    accent: rgb(0.85, 0.55, 0.05), // Amber Gold
  };

  // Top Banner
  const bannerHeight = 68;
  const bannerTop = pageHeight - margin;
  page.drawRectangle({
    x: margin,
    y: bannerTop - bannerHeight,
    width: contentWidth,
    height: bannerHeight,
    color: theme.primary,
  });

  page.drawText('SWA DIAMONDS', {
    x: margin + 16,
    y: bannerTop - 25,
    size: 15,
    font: bold,
    color: rgb(1, 1, 1),
  });

  page.drawText('EVENT SPONSORSHIP & PROMOTION APPROVAL FORM', {
    x: margin + 16,
    y: bannerTop - 46,
    size: 10.5,
    font: bold,
    color: theme.subText,
  });

  const badgeText = `Budget: Rs. ${Number(d.total_budget || d.total_incl_gst || req.amount || 0).toLocaleString('en-IN', {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  })}`;
  const badgeSafe = toSafePdfText(badgeText);
  const badgeW = bold.widthOfTextAtSize(badgeSafe, 9.5);
  const pillW = badgeW + 20;
  page.drawRectangle({
    x: margin + contentWidth - pillW - 12,
    y: bannerTop - 44,
    width: pillW,
    height: 24,
    color: rgb(1, 1, 1),
  });
  page.drawText(badgeSafe, {
    x: margin + contentWidth - pillW - 2,
    y: bannerTop - 36,
    size: 9.5,
    font: bold,
    color: theme.primary,
  });

  let y = bannerTop - bannerHeight - 16;

  const drawSectionHeader = (title: string) => {
    page.drawRectangle({
      x: margin,
      y: y - 1,
      width: contentWidth,
      height: 16,
      color: rgb(0.93, 0.95, 0.98),
    });
    page.drawText(toSafePdfText(title), {
      x: margin + 8,
      y: y + 3,
      size: 9,
      font: bold,
      color: theme.primary,
    });
    y -= 18;
  };

  const drawRow = (label: string, value: string, isAlt: boolean = false) => {
    const rowH = 15;
    if (isAlt) {
      page.drawRectangle({
        x: margin,
        y: y - 2,
        width: contentWidth,
        height: rowH,
        color: theme.rowAlt,
      });
    }
    page.drawText(toSafePdfText(label), {
      x: margin + 8,
      y: y + 2,
      size: 8.2,
      font: bold,
      color: rgb(0.25, 0.3, 0.38),
    });
    page.drawText(toSafePdfText(value), {
      x: margin + 175,
      y: y + 2,
      size: 8.2,
      font: regular,
      color: rgb(0.1, 0.1, 0.12),
    });
    y -= rowH;
  };

  // Section 1: Request & Shop Details
  drawSectionHeader('1. REQUEST & CONDUCTING SHOP DETAILS');
  const exhShopName = String(d.conducting_shop_name || req.shop_name || 'Not Assigned').trim();
  drawRow('Request Number', req.request_no || 'Pending Assignment', false);
  drawRow('Submitted Date', formatISTDate(req.submitted_at || req.created_at, true), true);
  drawRow('Requested By', req.requester_name || '-', false);
  drawRow('Conducting Shop', exhShopName, true);
  drawRow('Event Name', String(d.event_name || req.title || '-'), false);
  drawRow('Organiser & Contact', String(d.organiser_contact || '-'), true);
  drawRow('Venue / Location', String(d.venue || '-'), false);

  y -= 4;

  // Section 2: Event Window & Daily Schedule (HIGHLIGHTED PART)
  drawSectionHeader(`2. EVENT SCHEDULE · ${totalDays} DAY${totalDays === 1 ? '' : 'S'} (${totalHours.toFixed(1)} HOURS TOTAL)`);
  
  // Highlight box
  page.drawRectangle({
    x: margin,
    y: y - 18,
    width: contentWidth,
    height: 22,
    color: rgb(0.94, 0.97, 1.0),
    borderColor: rgb(0.7, 0.8, 0.95),
    borderWidth: 0.8,
  });
  const windowSummary = toSafePdfText(
    `Event Window: ${d.event_dates || '-'}${totalDays > 0 ? ` · Total Duration: ${totalDays} Day(s) · ${totalHours.toFixed(1)} Hours` : ''}`
  );
  page.drawText(windowSummary, {
    x: margin + 10,
    y: y - 10,
    size: 8.5,
    font: bold,
    color: theme.primary,
  });
  y -= 26;

  // Daily Schedule Table
  if (schedules.length > 0) {
    const tableHeaderY = y;
    page.drawRectangle({
      x: margin,
      y: tableHeaderY - 2,
      width: contentWidth,
      height: 16,
      color: rgb(0.88, 0.92, 0.98),
    });
    page.drawText('DAY #', { x: margin + 8, y: tableHeaderY + 2, size: 7.8, font: bold, color: theme.primary });
    page.drawText('DATE & DAY', { x: margin + 60, y: tableHeaderY + 2, size: 7.8, font: bold, color: theme.primary });
    page.drawText('FROM TIME', { x: margin + 220, y: tableHeaderY + 2, size: 7.8, font: bold, color: theme.primary });
    page.drawText('TO TIME', { x: margin + 310, y: tableHeaderY + 2, size: 7.8, font: bold, color: theme.primary });
    page.drawText('DURATION (HOURS)', { x: margin + 400, y: tableHeaderY + 2, size: 7.8, font: bold, color: theme.primary });
    y -= 17;

    schedules.slice(0, 10).forEach((s, idx) => {
      const isAlt = idx % 2 === 1;
      if (isAlt) {
        page.drawRectangle({
          x: margin,
          y: y - 1,
          width: contentWidth,
          height: 14,
          color: theme.rowAlt,
        });
      }
      page.drawText(`Day ${s.day_number || idx + 1}`, {
        x: margin + 8,
        y: y + 2,
        size: 7.8,
        font: bold,
        color: rgb(0.2, 0.25, 0.35),
      });
      page.drawText(toSafePdfText(s.day_name ? `${s.date} (${s.day_name})` : s.date), {
        x: margin + 60,
        y: y + 2,
        size: 7.8,
        font: regular,
        color: rgb(0.1, 0.1, 0.15),
      });
      page.drawText(toSafePdfText(s.from_time || '-'), {
        x: margin + 220,
        y: y + 2,
        size: 7.8,
        font: regular,
        color: rgb(0.1, 0.1, 0.15),
      });
      page.drawText(toSafePdfText(s.to_time || '-'), {
        x: margin + 310,
        y: y + 2,
        size: 7.8,
        font: regular,
        color: rgb(0.1, 0.1, 0.15),
      });
      page.drawText(`${Number(s.hours || 0).toFixed(1)} hrs`, {
        x: margin + 400,
        y: y + 2,
        size: 7.8,
        font: bold,
        color: theme.primary,
      });
      y -= 14;
    });

    // Summary row
    page.drawRectangle({
      x: margin,
      y: y - 1,
      width: contentWidth,
      height: 15,
      color: rgb(0.92, 0.95, 0.99),
    });
    page.drawText(`TOTAL DURATION: ${totalDays} DAY(S)`, {
      x: margin + 8,
      y: y + 2.5,
      size: 8,
      font: bold,
      color: theme.primary,
    });
    page.drawText(`${totalHours.toFixed(1)} HOURS TOTAL`, {
      x: margin + 400,
      y: y + 2.5,
      size: 8,
      font: bold,
      color: theme.primary,
    });
    y -= 17;
  }

  y -= 4;

  // Section 3: Sponsorship Financials
  drawSectionHeader('3. SPONSORSHIP & FINANCIALS');
  drawRow('Amount (excl. GST)', `Rs. ${Number(d.amount_excl_gst || 0).toLocaleString('en-IN', { minimumFractionDigits: 2 })}`, false);
  drawRow(`GST (${Number(d.gst_pct || 0)}%)`, `Rs. ${Number(d.gst_amount || 0).toLocaleString('en-IN', { minimumFractionDigits: 2 })}`, true);
  drawRow('Total (incl. GST)', `Rs. ${Number(d.total_incl_gst || req.amount || 0).toLocaleString('en-IN', { minimumFractionDigits: 2 })}`, false);
  drawRow('Payment Mode & Due Date', String(d.payment_mode_due || 'As per agreement'), true);
  drawRow('Organiser GSTIN', String(d.organiser_gstin || 'Unregistered / Not Provided'), false);
  drawRow('GST Invoice Provided', d.gst_invoice ? 'Yes — Tax invoice provided' : 'No', true);

  y -= 4;

  // Section 4: Promotion Plan & Budget
  drawSectionHeader('4. PROMOTION PLAN & BUDGET');
  const providesList = (Array.isArray(d.provides) ? d.provides : []).map((p: string) => PROVIDE_NAMES[p] || p);
  if (d.provides_other) providesList.push(`Other: ${d.provides_other}`);
  drawRow('Organiser Provides', providesList.length > 0 ? providesList.join('  ·  ') : '—', false);
  drawRow('Rs. 1,000 Vouchers (Qty)', d.voucher_1000_qty ? `${d.voucher_1000_qty} pcs` : 'None', true);
  drawRow('Rs. 500 Vouchers (Qty)', d.voucher_500_qty ? `${d.voucher_500_qty} pcs` : 'None', false);
  drawRow('Voucher Validity', String(d.voucher_validity || 'Standard'), true);
  drawRow('Lucky Draw Prize & Value', String(d.lucky_draw || '—'), false);
  drawRow('Other Costs (Printing/Branding)', `Rs. ${Number(d.other_costs || 0).toLocaleString('en-IN', { minimumFractionDigits: 2 })}`, true);
  drawRow('Total Event Budget', `Rs. ${Number(d.total_budget || d.total_incl_gst || req.amount || 0).toLocaleString('en-IN', { minimumFractionDigits: 2 })}`, false);

  y -= 4;

  // Section 5: Purpose & Deliverables
  drawSectionHeader('5. PURPOSE & EXPECTED RESULT');
  const purposeLines = wrapText(String(d.purpose || req.notes || '-'), regular, 8, contentWidth - 20);
  for (const line of purposeLines.slice(0, 4)) {
    page.drawText(line, {
      x: margin + 8,
      y,
      size: 8,
      font: regular,
      color: rgb(0.15, 0.15, 0.18),
    });
    y -= 11;
  }

  // Footer / Workflow Info
  const footerY = margin + 14;
  page.drawLine({
    start: { x: margin, y: footerY + 12 },
    end: { x: margin + contentWidth, y: footerY + 12 },
    thickness: 0.5,
    color: rgb(0.8, 0.85, 0.9),
  });
  page.drawText(
    toSafePdfText('Workflow: Route A — Department Head Review & Administrator Approval Required · Stamped Official Approval Form'),
    {
      x: margin,
      y: footerY,
      size: 7.2,
      font: regular,
      color: rgb(0.4, 0.45, 0.55),
    }
  );
  page.drawText(toSafePdfText('Page 1 of 1'), {
    x: margin + contentWidth - 45,
    y: footerY,
    size: 7.2,
    font: regular,
    color: rgb(0.4, 0.45, 0.55),
  });

  const pdfBytes = await pdfDoc.save();
  const pdfBlob = new Blob([pdfBytes as BlobPart], { type: 'application/pdf' });
  return {
    bytes: pdfBytes,
    blob: pdfBlob,
    pageCount: 1,
    fileName: EXHIBITION_FORM_FILE_NAME,
  };
}

import React, { useState } from 'react';
import { CheckCircle2, Download, ExternalLink, FileCheck, Loader2 } from 'lucide-react';
import { RequestRecord, RequestFile } from '../../types/database';
import { useAuth } from '../../context/AuthContext';
import { downloadStoredFile, useSignedUrl } from '../../lib/files';
import { VoicePlayer } from './VoicePlayer';

/** Approved / paid: signed packet + each stamped document, each downloadable. */
export const SignedDocuments: React.FC<{ request: RequestRecord }> = ({ request }) => {
  const { isBackendConnected } = useAuth();
  const [busy, setBusy] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const signed = [...(request.signed_files || [])].sort((a, b) => Number(!!b.is_packet) - Number(!!a.is_packet));

  const download = async (path: string, name: string, key: string) => {
    setError(null);
    if (!isBackendConnected) {
      setError('Sandbox mode: signed PDFs are only generated by the live server.');
      return;
    }
    setBusy(key);
    const res = await downloadStoredFile('signed-documents', path, name);
    setBusy(null);
    if (!res.success) setError(res.error || 'Download failed');
  };

  const packet = signed.find((s) => s.is_packet) || signed[0];

  return (
    <div className="bg-emerald-50/70 border border-emerald-200 rounded-2xl p-5 shadow-xs space-y-4">
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div className="flex items-start gap-3">
          <div className="w-10 h-10 rounded-xl bg-emerald-600 text-white flex items-center justify-center shrink-0 shadow-sm">
            <CheckCircle2 className="w-5 h-5" />
          </div>
          <div>
            <h4 className="font-bold text-slate-900 text-sm">Official Signed Approval Packet</h4>
            <p className="text-xs text-slate-600 mt-0.5">
              Approval No: <span className="font-mono font-bold">{request.approval_no}</span> • Stamped with seal, signature &amp; date-time
            </p>
            {request.verify_token && (
              <a
                href={`/verify/${request.verify_token}`}
                target="_blank"
                rel="noreferrer"
                className="inline-flex items-center gap-1 text-[11px] font-semibold text-emerald-800 hover:text-emerald-950 mt-1 underline"
              >
                <span>Verification page</span>
                <ExternalLink className="w-3 h-3" />
              </a>
            )}
          </div>
        </div>

        {packet && (
          <button
            type="button"
            id="download-signed-packet"
            onClick={() => download(packet.storage_path, packet.file_name || `${request.approval_no}_packet.pdf`, packet.id)}
            disabled={busy === packet.id}
            className="inline-flex items-center justify-center gap-2 px-4 py-2.5 rounded-xl bg-emerald-600 hover:bg-emerald-700 text-white font-semibold text-xs shadow-md shadow-emerald-200 transition-all shrink-0 disabled:opacity-60"
          >
            {busy === packet.id ? <Loader2 className="w-4 h-4 animate-spin" /> : <Download className="w-4 h-4" />}
            <span>Download Signed PDF</span>
          </button>
        )}
      </div>

      {signed.length > 1 && (
        <ul className="divide-y divide-emerald-100 bg-white/70 rounded-xl border border-emerald-100">
          {signed.map((s) => {
            const name = s.file_name || s.storage_path.split('/').pop() || 'document.pdf';
            return (
              <li key={s.id} className="flex items-center gap-2 px-3 py-2 text-xs">
                <FileCheck className="w-4 h-4 text-emerald-600 shrink-0" />
                <span className="flex-1 truncate font-medium text-slate-700">
                  {s.is_packet ? 'Complete packet (cover + all pages)' : name}
                </span>
                <span className="text-[10px] text-slate-400 shrink-0">{s.page_count} pg</span>
                <span className="hidden sm:inline font-mono text-[10px] text-slate-400" title={s.sha256}>
                  {s.sha256.slice(0, 10)}…
                </span>
                <button
                  type="button"
                  onClick={() => download(s.storage_path, name, s.id)}
                  disabled={busy === s.id}
                  className="p-1.5 rounded-lg text-emerald-700 hover:bg-emerald-50 disabled:opacity-50"
                  aria-label={`Download ${name}`}
                >
                  {busy === s.id ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <Download className="w-3.5 h-3.5" />}
                </button>
              </li>
            );
          })}
        </ul>
      )}

      {isBackendConnected && signed.length === 0 && (
        <p className="text-[11px] text-emerald-800">Signed files are being prepared. Refresh in a moment.</p>
      )}
      {error && <div className="p-2.5 bg-amber-50 border border-amber-200 rounded-lg text-[11px] text-amber-800">{error}</div>}
    </div>
  );
};

/** Voice note player that resolves a short-lived URL in live mode. */
export const VoiceNoteItem: React.FC<{ file: RequestFile }> = ({ file }) => {
  const { isBackendConnected } = useAuth();
  const signed = useSignedUrl('request-files', file.storage_path, isBackendConnected);
  return (
    <VoicePlayer
      url={isBackendConnected ? signed.url || undefined : file.public_url}
      duration={file.duration_sec}
      title={file.original_name}
    />
  );
};
